"""Chromium interaction test for the offline floor-plan demo; backend patches tested separately."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parent.parent
css=(ROOT/'style.css').read_text()
js=(ROOT/'app.js').read_text()
mock="<script>window.fetch=async()=>new Response('{\"error\":\"standalone\"}',{status:404,headers:{'Content-Type':'application/json'}});</script>"
html='<html><head><meta name="viewport" content="width=device-width, initial-scale=1"><style>'+css+'</style></head><body><div id="app"></div>'+mock+'<script>'+js+'</script></body></html>'
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    page=context.new_page();page.set_default_timeout(6000)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html,wait_until='domcontentloaded');page.wait_for_timeout(200)
    expect(page.locator('.floor-board')).to_be_visible()
    expect(page.locator('.floor-piece')).to_have_count(6)
    expect(page.locator('.sidebar')).to_be_hidden()
    expect(page.locator('.till-quicknav')).to_be_visible()
    assert page.locator('.statgrid').count()==0
    page.screenshot(path=str(ROOT/'screenshots/screenshot-v04-till-inside.png'),full_page=True)
    page.locator('[data-zone="Terrace"]').click()
    expect(page.locator('.floor-piece')).to_have_count(4)
    page.screenshot(path=str(ROOT/'screenshots/screenshot-v04-till-terrace.png'),full_page=True)
    page.locator('[data-zone="Main room"]').click()
    page.locator('[data-table="m1"]').click()
    expect(page.locator('.floor-drawer')).to_be_visible()
    page.locator('[data-action="close-floor-inspector"]').last.click()
    expect(page.locator('.floor-drawer')).to_have_count(0)
    page.locator('.till-quicknav [data-workspace="manager"]').click()
    expect(page.get_by_role('heading',name='Floor designer')).to_be_visible()
    expect(page.locator('.floor-edit-board')).to_be_visible()
    m1=page.locator('[data-designer-table="m1"]')
    original=m1.get_attribute('style')
    bounds=m1.bounding_box()
    page.mouse.move(bounds['x']+bounds['width']/2,bounds['y']+bounds['height']/2)
    page.mouse.down();page.mouse.move(bounds['x']+bounds['width']/2+140,bounds['y']+bounds['height']/2+70,steps=12);page.mouse.up()
    moved=page.locator('[data-designer-table="m1"]').get_attribute('style')
    assert original!=moved,(original,moved)
    page.locator('[data-form="designer-table"] [name="tableName"]').fill('Table 11')
    page.locator('[data-form="designer-table"] [name="shape"]').select_option('round')
    page.locator('[data-form="designer-table"] button[type="submit"]').click()
    assert 'shape-round' in page.locator('[data-designer-table="m1"]').get_attribute('class')
    page.locator('[data-form="area-add"] [name="name"]').fill('Garden')
    page.locator('[data-form="area-add"] button[type="submit"]').click()
    expect(page.locator('[data-zone="Garden"]')).to_be_visible()
    page.locator('[data-form="designer-add"] [name="tableName"]').fill('Garden 1')
    page.locator('[data-form="designer-add"] button[type="submit"]').click()
    expect(page.locator('[data-designer-table]')).to_have_count(1)
    page.screenshot(path=str(ROOT/'screenshots/screenshot-v04-floor-designer.png'),full_page=True)
    page.locator('[data-workspace="service"]:visible').first.click()
    expect(page.locator('[data-zone="Garden"]')).to_be_visible()
    page.locator('[data-table]').first.click()
    expect(page.locator('.floor-drawer')).to_be_visible()
    page.locator('[data-action="seat"]').click()
    page.locator('[name="covers"]').fill('3')
    page.locator('[data-form="covers"] button[type="submit"]').click()
    page.locator('[data-action="goto-order"]').click()
    expect(page.get_by_role('heading',name='Waiter POS')).to_be_visible()
    page.locator('[data-nav="floor"]:visible').first.click()
    page.locator('[data-zone="Main room"]').click()
    assert page.locator('[data-table="m1"]').inner_text().startswith('Table 11')
    assert 'shape-round' in page.locator('[data-table="m1"]').get_attribute('class')
    # Narrow viewport: large touch floor plan and table drawer still function.
    mobile=context.new_page();mobile.set_viewport_size({'width':390,'height':844});mobile.set_content(html,wait_until='domcontentloaded')
    expect(mobile.locator('.floor-board')).to_be_visible()
    mobile.screenshot(path=str(ROOT/'screenshots/screenshot-v04-mobile.png'),full_page=True)
    mobile.locator('[data-table="m1"]').click()
    expect(mobile.locator('.floor-drawer')).to_be_visible()
    assert not errors,errors
    print('PASS: full-screen-oriented floor, room switching, table drawer, dragging, rename, shapes, new area, seating, and mobile. JS errors:',errors)
    browser.close()
